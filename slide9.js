// Η fetch() στέλνει αιτήματα HTTP σε κάποιο server/API στο παρασκήνιο
// χωρίς να χρειαστεί να ξαναφορτώσει η σελίδα.

fetch("https://api.github.com/users/octocat") // Στέλνει το αίτημα και λαμβάνει ένα Promise
    .then(res => res.json())                  // Μετατρέπει την απάντηση του server σε JSON
    .then(data => {                           // Χρησιμοποιούνται τα δεδομένα
        console.log(data);
    })
    .catch(err => console.error(err));        // Διαχείριση σφάλματος (π.χ. διακοπή σύνδεσης)
